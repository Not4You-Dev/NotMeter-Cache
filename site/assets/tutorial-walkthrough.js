globalThis.NotMeterApplyWalkthrough = (copy, language) => {
  if (copy.walkthroughApplied) return;
  const t = globalThis.NotMeterTutorialWalkthrough[language];
  const add = (id, source, related, screens=[]) => { copy.articles[id]={title:source[0],intro:source[1],steps:source[2],notes:source[3],related,screens}; };
  add('resources',t.energy,['dailyPoints','Display','Hotkeys','locks']);
  add('dailyPoints',t.points,['resources','Display','locks']);
  add('artifact',t.artifact,['Hotkeys','dailyPoints']);
  add('locks',globalThis.NotMeterTutorialLocks[language],['General','Hotkeys','details']);
  for (const [id, step] of Object.entries(t.extra)) copy.articles[id].steps.push(step);
  copy.articles.reading.steps[3]=t.camera;
  copy.articles.reading.steps.push(t.reset);
  copy.articles.CombatRecords.steps.push(...t.recordSteps);
  copy.articles.reading.related.unshift('locks','resources','dailyPoints');
  copy.articles.General.related.unshift('locks');
  copy.articles.Hotkeys.related.push('artifact');
  copy.scenes.hunting=[t.huntingTitle,t.points[2][5],t.points[2][6],t.points[3][0],[t.huntingTitle]];
  copy.scenes.artifact=[t.artifact[0],t.artifact[2][1],t.artifact[2][2],t.artifact[2][3],[t.artifact[2][3]]];
  const lock=globalThis.NotMeterTutorialLocks[language];
  copy.scenes.locks=[lock[0],lock[2][0],lock[2][1],lock[2][2],lock[4]];
  for (const article of Object.values(copy.articles)) {
    article.related=[...new Set(article.related)];
    article.screens=[...new Set(article.screens)];
  }
  copy.walkthroughApplied=true;
};
